  /// The log as a growing list (newest last, at most [maxEntries]), handling
  /// resets and clears - convenient for a log screen.
  Stream<List<SingBoxLogEntry>> watchLogBuffer({int maxEntries = 1000}) {
    final buffer = <SingBoxLogEntry>[];
    return watchLogEvents().map((event) {
      switch (event) {
        case SingBoxLogBatch(:final entries, :final reset):
          if (reset) buffer.clear();
          buffer.addAll(entries);
          final overflow = buffer.length - maxEntries;
          if (overflow > 0) buffer.removeRange(0, overflow);
        case SingBoxLogCleared():
          buffer.clear();
        case SingBoxLogDefaultLevel():
          break;
      }
      return List<SingBoxLogEntry>.unmodifiable(buffer);
    });
  }

