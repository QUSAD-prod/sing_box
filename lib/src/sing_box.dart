  // ===========================================================================
  // Connection
  // ===========================================================================

  /// The current tunnel status (cached, updated in real time).
  SingBoxConnectionStatus get status => _state.status;

  /// The current tunnel state including start time and last error.
  SingBoxConnectionState get state => _state;

  /// Whether the tunnel is connected.
  bool get isConnected => _state.status == SingBoxConnectionStatus.connected;

  /// Starts the VPN with [config] (share link(s), outbound JSON or a complete
  /// sing-box config - see the class documentation).
  ///
  /// The generated configuration is validated by sing-box before the tunnel
  /// starts. When the VPN permission is missing it is requested first (set
  /// [requestPermission] to `false` to throw a [SingBoxPermissionException]
  /// instead). If the tunnel is already running it is reloaded with the new
  /// configuration.
  ///
  /// Completes when the start was requested; follow
  /// [watchConnectionStatus] for the result. Throws
  /// [SingBoxConfigException], [SingBoxPermissionException] or another
  /// [SingBoxException].
  Future<void> connect(
    String config, {
    SingBoxRoutingRules? rules,
    SingBoxConfigOptions? options,
    bool applyRules = true,
    bool requestPermission = true,
    String? selectedTag,
  }) async {
    _ensureInitialized();
    final finalConfig = await buildConfig(
      config,
      rules: rules,
      options: options,
      applyRules: applyRules,
      selectedTag: selectedTag,
    );
    await _startTunnel(finalConfig, requestPermission: requestPermission);
    await _rememberInput(config, applyRules: applyRules, selectedTag: selectedTag);
  }

  /// Connects using the stored server profile [server] and makes it the
  /// active server.
  Future<void> connectToServer(
    SingBoxServerConfig server, {
    bool requestPermission = true,
  }) async {
    await connect(server.config, requestPermission: requestPermission);
    await _setActiveId(server.id);
  }

  /// Connects to the active server profile (see [setActiveServerConfig]).
  ///
  /// Throws a [SingBoxConfigException] when no active server is set.
  Future<void> connectToActiveServer({bool requestPermission = true}) async {
    final active = await getActiveServerConfig();
    if (active == null) {
      throw const SingBoxConfigException('No active server configuration.');
    }
    await connectToServer(active, requestPermission: requestPermission);
  }

  /// Connects with several server profiles combined into one configuration:
  /// a `selector` group ([SingBoxConfigBuilder.proxyTag]) with an automatic
  /// `urltest` member ([SingBoxConfigBuilder.autoTag]).
  ///
  /// Switching between them later is instant with [selectOutbound] - no
  /// reconnect needed. Disabled profiles and complete configs are skipped.
  /// [selectedId] selects a profile initially (default: automatic selection
  /// by latency).
  Future<void> connectToServers(
    List<SingBoxServerConfig> servers, {
    String? selectedId,
    bool requestPermission = true,
  }) async {
    final outbounds = <Map<String, dynamic>>[];
    final usedTags = <String>{};
    String? selectedTag;
    for (final server in servers) {
      if (!server.enabled) continue;
      final outbound = server.outbound;
      if (outbound == null) continue;
      var tag = server.name.isNotEmpty ? server.name : server.id;
      if (_reservedTags.contains(tag) || usedTags.contains(tag)) {
        var index = 2;
        while (usedTags.contains('$tag ($index)')) {
          index++;
        }
        tag = '$tag ($index)';
      }
      usedTags.add(tag);
      outbounds.add({...outbound, 'tag': tag});
      if (server.id == selectedId) selectedTag = tag;
    }
    if (outbounds.isEmpty) {
      throw const SingBoxConfigException(
        'None of the servers can be combined (all disabled or complete configs).',
      );
    }
    await connect(
      jsonEncode(outbounds),
      selectedTag: selectedTag,
      requestPermission: requestPermission,
    );
    if (selectedId != null) await _setActiveId(selectedId);
  }

  static const _reservedTags = {
    SingBoxConfigBuilder.proxyTag,
    SingBoxConfigBuilder.autoTag,
    SingBoxConfigBuilder.directTag,
  };

  Future<void> _startTunnel(
    String config, {
    required bool requestPermission,
  }) async {
    if (!await _platform.hasVpnPermission()) {
      final granted =
          requestPermission && await _platform.requestVpnPermission();
      if (!granted) {
        const error = SingBoxPermissionException(
          'The VPN permission was not granted.',
        );
        _observer.onConnectionError(error.message);
        throw error;
      }
    }
    final settings = await getSettings();
    _observer.onConnect(config);
    try {
      await _platform.start(
        config,
        disableMemoryLimit: settings.disableMemoryLimit,
      );
      _observer.info('Tunnel start requested');
    } on SingBoxException catch (e, s) {
      _observer.onConnectionError(e.message);
      _observer.error('Failed to start the tunnel', e, s);
      rethrow;
    }
  }

  /// Stops the VPN.
  Future<void> disconnect() async {
    _ensureInitialized();
    _observer.onDisconnect();
    try {
      await _platform.stop();
    } on SingBoxException catch (e, s) {
      _observer.error('Failed to stop the tunnel', e, s);
      rethrow;
    }
  }

  /// Stops and starts the tunnel again with the last configuration.
  Future<void> restart({Duration timeout = const Duration(seconds: 10)}) async {
    _ensureInitialized();
    final config = await _platform.getLastConfig();
    if (config == null) {
      throw const SingBoxConfigException('There is no configuration to restart.');
    }
    if (_state.status != SingBoxConnectionStatus.disconnected) {
      await disconnect();
      await waitForStatus(SingBoxConnectionStatus.disconnected, timeout: timeout);
    }
    await _startTunnel(config, requestPermission: false);
  }

  /// Reloads the running tunnel without tearing down the VPN interface,
  /// optionally with a new complete [config] (used verbatim).
  ///
  /// Throws a [SingBoxServiceNotRunningException] when the tunnel is stopped.
  Future<void> reload([String? config]) {
    _ensureInitialized();
    return _platform.reload(config);
  }

  /// Switches to another server configuration ([config] accepts the same
  /// input as [connect]).
  ///
  /// When connected, the running tunnel is reloaded in place (no VPN
  /// interface restart, so no permission prompts and minimal downtime);
  /// otherwise this is the same as [connect].
  Future<void> switchServer(String config) async {
    _ensureInitialized();
    if (!_state.status.isActive) {
      await connect(config);
      return;
    }
    final finalConfig = await buildConfig(config);
    await _platform.checkConfig(finalConfig);
    await _platform.reload(finalConfig);
    await _rememberInput(config, applyRules: true);
  }

  /// Rebuilds the configuration from the last [connect] input with the
  /// current routing rules and [configOptions], and reloads the running
  /// tunnel. Does nothing when disconnected.
  Future<void> reapplyRules() async {
    _ensureInitialized();
    if (!_state.status.isActive) return;
    final last = await _storage.readMap(SingBoxStorage.keyLastInput);
    final input = last?['input'] as String?;
    if (input == null) {
      _observer.info('Rules will be applied on the next connect');
      return;
    }
    final config = await buildConfig(
      input,
      applyRules: last?['applyRules'] as bool? ?? true,
      selectedTag: last?['selectedTag'] as String?,
    );
    await _platform.checkConfig(config);
    await _platform.reload(config);
    _observer.info('Routing rules re-applied');
  }

  Future<void> _rememberInput(
    String input, {
    required bool applyRules,
    String? selectedTag,
  }) {
    return _storage.writeJson(SingBoxStorage.keyLastInput, {
      'input': input,
      'applyRules': applyRules,
      'selectedTag': ?selectedTag,
    });
  }

  /// Returns the last configuration passed to the native side (the final,
  /// generated config), or `null`.
  Future<String?> getLastConfig() {
    _ensureInitialized();
    return _platform.getLastConfig();
  }

  /// Queries the tunnel status from the native side.
  Future<SingBoxConnectionStatus> getConnectionStatus() async {
    _ensureInitialized();
    try {
      return await _platform.getStatus();
    } on SingBoxException catch (e, s) {
      _observer.error('Failed to get the status', e, s);
      return _state.status;
    }
  }

  /// Emits the tunnel status: the current value first, then every change.
  Stream<SingBoxConnectionStatus> watchConnectionStatus() =>
      watchConnectionState().map((state) => state.status).distinct();

  /// Emits the full tunnel state: the current value first, then every
  /// change. Use it to show the connection time ([SingBoxConnectionState.startedAt])
  /// or the error that stopped the tunnel ([SingBoxConnectionState.error]).
  Stream<SingBoxConnectionState> watchConnectionState() async* {
    _ensureInitialized();
    yield _state;
    yield* _stateController.stream;
  }

  /// Completes when the tunnel reaches [status], or throws a
  /// [TimeoutException] after [timeout].
  Future<void> waitForStatus(
    SingBoxConnectionStatus status, {
    Duration timeout = const Duration(seconds: 30),
  }) {
    return watchConnectionStatus()
        .firstWhere((s) => s == status)
        .timeout(timeout);
  }

  /// Same as [watchConnectionStatus].
  @Deprecated('Use watchConnectionStatus() instead.')
  Stream<SingBoxConnectionStatus> watchSingBoxConnectionStatus() =>
      watchConnectionStatus();

  // ===========================================================================
  // Statistics, logs, notifications
  // ===========================================================================

  /// Real-time traffic statistics, about once per second while connected.
  /// [SingBoxConnectionStats.duration] is filled from the session start time.
  Stream<SingBoxConnectionStats> watchConnectionStats() {
    _ensureInitialized();
    return _platform.watchStats().map((stats) {
      final withDuration = stats.copyWith(duration: _state.duration);
      _lastStats = withDuration;
      _observer.onConnectionStatsChanged(withDuration);
      return withDuration;
    });
  }

  /// Same as [watchConnectionStats].
  @Deprecated('Use watchConnectionStats() instead.')
  Stream<SingBoxConnectionStats> watchSingBoxConnectionStats() =>
      watchConnectionStats();

  /// Returns the latest statistics. Waits up to [timeout] for a fresh sample
  /// when none was received yet; returns [SingBoxConnectionStats.empty] when
  /// disconnected.
  Future<SingBoxConnectionStats> getConnectionStats({
    Duration timeout = const Duration(seconds: 3),
  }) async {
    _ensureInitialized();
    if (!isConnected) return SingBoxConnectionStats.empty;
    final cached = _lastStats;
    if (cached != null) return cached.copyWith(duration: _state.duration);
    try {
      return await watchConnectionStats().first.timeout(timeout);
    } on Object catch (e) {
      _observer.debug('No statistics received', {'error': '$e'});
      return SingBoxConnectionStats.empty.copyWith(duration: _state.duration);
    }
  }

  /// Raw log events of the core (batches, reset, clear, default level).
  Stream<SingBoxLogEvent> watchLogEvents() {
    _ensureInitialized();
    return _platform.watchLogEvents();
  }

  /// Log entries of the core, one by one. The first batch after subscribing
  /// contains the lines buffered by the core so far.
  Stream<SingBoxLogEntry> watchLogs() => watchLogEvents().expand(
    (event) => event is SingBoxLogBatch ? event.entries : const <SingBoxLogEntry>[],
  );

  /// The log as a growing list (newest last, at most [maxEntries]), handling
  /// resets and clears - convenient for a log screen.
  Stream<List<SingBoxLogEntry>> watchLogBuffer({int maxEntries = 1000}) {
    final buffer = <SingBoxLogEntry>[];
    return watchLogEvents().map((event) {
      switch (event) {
        case SingBoxLogBatch(:final entries, :final reset):
          if (reset) buffer.clear();
          buffer.addAll(entries);
          final overflow = buffer.length - maxEntries;
          if (overflow > 0) buffer.removeRange(0, overflow);
        case SingBoxLogCleared():
          buffer.clear();
        case SingBoxLogDefaultLevel():
          break;
      }
      return List<SingBoxLogEntry>.unmodifiable(buffer);
    });
  }

  /// Clears the log buffer of the core.
  Future<void> clearLogs() {
    _ensureInitialized();
    return _platform.clearLogs();
  }

  /// Notifications emitted by the sing-box core (for example rule-set update
  /// failures).
  Stream<SingBoxNotification> watchNotifications() {
    _ensureInitialized();
    return _platform.watchNotifications();
  }

