  /// Imports share links or a subscription body (base64 or one link per
  /// line) as new profiles and returns them. Unsupported lines are skipped.
  Future<List<SingBoxServerConfig>> importServerConfigs(
    String content, {
    String? subscriptionId,
  }) {
    return _synchronized(() async {
      final outbounds = SingBoxShareLink.parseSubscription(content);
      final servers = await getServerConfigs();
      final ids = servers.map((s) => s.id).toSet();
      final imported = <SingBoxServerConfig>[];
      for (final outbound in outbounds) {
        var id = outbound.tag;
        var index = 2;
        while (ids.contains(id)) {
          id = '${outbound.tag}-${index++}';
        }
        ids.add(id);
        imported.add(
          SingBoxServerConfig.fromOutbound(
            outbound.json,
            id: id,
            name: outbound.name ?? outbound.tag,
            link: outbound.link,
            subscriptionId: subscriptionId,
          ),
        );
      }
      if (imported.isNotEmpty) {
        await _writeServers([...servers, ...imported]);
        for (final s in imported) {
          _observer.onServerConfigAdded(s.id, s.name);
        }
      }
      return imported;
    });
  }

