/// The entry point of the plugin: controls the sing-box VPN tunnel.
///
/// `SingBox` is a singleton available as [SingBox.instance]. Call
/// [initialize] once, as early as possible (usually in `main`), then use the
/// rest of the API from anywhere in the app:
///
/// ```dart
/// Future<void> main() async {
///   WidgetsFlutterBinding.ensureInitialized();
///   await SingBox.instance.initialize();
///   runApp(const MyApp());
/// }
///
/// // Connect with a share link, an outbound JSON or a complete config.
/// await SingBox.instance.connect('vless://uuid@example.com:443?security=reality&...#My server');
///
/// SingBox.instance.watchConnectionStatus().listen(print);
/// SingBox.instance.watchConnectionStats().listen((s) => print(s.downloadSpeed));
///
/// await SingBox.instance.disconnect();
/// ```
///
/// Configuration input accepted by [connect], [switchServer] and
/// [buildConfig]:
///
/// * a **share link** (`vless://`, `vmess://`, `trojan://`, `ss://`,
///   `hysteria2://`, `tuic://`, …) or several links / a base64 subscription -
///   a complete config with TUN, DNS and routing is generated by
///   [SingBoxConfigBuilder];
/// * a **single outbound** JSON object or a JSON **array of outbounds** -
///   also wrapped by [SingBoxConfigBuilder];
/// * a **complete sing-box configuration** - used as is, with the stored
///   [SingBoxRoutingRules] applied on top (unless `applyRules: false`).
///
/// Errors are reported as [SingBoxException] subclasses.
class SingBox {
  SingBox._();

  /// The single instance of the plugin API.
  static final SingBox instance = SingBox._();

  SingBoxPlatform get _platform => SingBoxPlatform.instance;

  final SingBoxStorage _storage = SingBoxStorage();

  bool _isInitialized = false;
  Future<void>? _initializing;
  SingBoxRuntimeInfo? _runtimeInfo;
  SingBoxObserver _observer = const SingBoxNoOpObserver();

  SingBoxConnectionState _state = SingBoxConnectionState.initial;
  final StreamController<SingBoxConnectionState> _stateController =
      StreamController<SingBoxConnectionState>.broadcast();
  StreamSubscription<SingBoxConnectionState>? _stateSubscription;
  StreamSubscription<SingBoxNotification>? _notificationSubscription;
  SingBoxConnectionStats? _lastStats;
  Future<void> _mutation = Future<void>.value();
  Future<void> _serviceQueue = Future<void>.value();
  int _connectGeneration = 0;
  _StartWaiter? _startWaiter;

  /// Default time [connect] waits for the tunnel to connect.
  static const defaultConnectTimeout = Duration(seconds: 30);

  /// Options used to generate configurations from share links and outbounds
  /// (TUN, DNS, logging, URL test, clash modes).
  ///
  /// Changing it does not affect a running tunnel until the next [connect]
  /// or [reapplyRules].
  SingBoxConfigOptions configOptions = const SingBoxConfigOptions();

  /// Whether a running tunnel is reloaded automatically when the routing
  /// rules change (bypass/block lists, DNS servers). Defaults to `true`.
  bool reloadOnRulesChange = true;

  // ===========================================================================
  // Lifecycle
  // ===========================================================================

  /// Whether [initialize] completed successfully.
  bool get isInitialized => _isInitialized;

  /// Information reported by the native side during [initialize].
  SingBoxRuntimeInfo? get runtimeInfo => _runtimeInfo;

  /// The current observer.
  SingBoxObserver get observer => _observer;

  /// Sets the [observer] that receives diagnostic events.
  ///
  /// ```dart
  /// SingBox.instance.setObserver(SingBoxTalkerObserver(Talker()));
  /// ```
  void setObserver(SingBoxObserver observer) {
    _observer = observer;
    _observer.debug('Observer set');
  }

  /// Initializes the plugin. Must be called before any other method,
  /// preferably in `main()` after `WidgetsFlutterBinding.ensureInitialized()`.
  ///
  /// Sets up the sing-box core, the Android notification channel and the iOS
  /// VPN profile, starts tracking the tunnel state, applies the stored
  /// [SingBoxSettings] to the native service and, when
  /// [SingBoxSettings.autoConnectOnStart] is enabled, connects to the active
  /// server.
  ///
  /// Calling it again is a no-op. Throws a [SingBoxException] on failure.
  Future<void> initialize([SingBoxOptions options = const SingBoxOptions()]) {
    if (_isInitialized) return Future<void>.value();
    return _initializing ??= _initialize(options).whenComplete(() {
      _initializing = null;
    });
  }

  Future<void> _initialize(SingBoxOptions options) async {
    _observer.info('Initializing sing_box');
    try {
      _runtimeInfo = await _platform.initialize(options);
      _state = SingBoxConnectionState(status: _runtimeInfo!.status);
      await _stateSubscription?.cancel();
      _stateSubscription = _platform.watchState().listen(
        _handleState,
        onError:
            (Object e, StackTrace s) =>
                _observer.error('Status stream error', e, s),
      );
      await _notificationSubscription?.cancel();
      _notificationSubscription = _platform.watchNotifications().listen(
        _observer.onNotification,
        onError:
            (Object e, StackTrace s) =>
                _observer.error('Notification stream error', e, s),
      );
      _isInitialized = true;
      _observer.info('sing_box initialized', {
        'singBoxVersion': _runtimeInfo!.singBoxVersion,
        'status': _state.status.name,
      });
    } on SingBoxException catch (e, s) {
      _observer.error('Failed to initialize sing_box', e, s);
      rethrow;
    }

    final settings = await getSettings();
    try {
      await _platform.setServiceOptions(settings.toServiceOptions());
    } on SingBoxException catch (e, s) {
      _observer.warning('Failed to apply service options', {'error': '$e'});
      _observer.debug('setServiceOptions stack', {'stack': '$s'});
    }
    if (settings.autoConnectOnStart && !_state.status.isActive) {
      unawaited(_autoConnect());
    }
  }

  Future<void> _autoConnect() async {
    try {
      final active = await getActiveServerConfig();
      if (active == null) {
        _observer.info('Auto-connect skipped: no active server');
        return;
      }
      if (!await hasVpnPermission()) {
        _observer.info('Auto-connect skipped: VPN permission not granted');
        return;
      }
      await connectToServer(active, requestPermission: false);
    } on Object catch (e, s) {
      _observer.error('Auto-connect failed', e, s);
    }
  }

  void _handleState(SingBoxConnectionState state) {
    final previous = _state;
    _state = state;
    if (state.status != SingBoxConnectionStatus.connected) _lastStats = null;
    if (previous.status != state.status) {
      _observer.onStatusChanged(state.status.name);
    }
    if (previous != state) {
      _observer.onConnectionStateChanged(state);
      if (state.error != null && state.error != previous.error) {
        _observer.onConnectionError(state.error!);
      }
    }
    _stateController.add(state);
  }

  void _ensureInitialized() {
    if (!_isInitialized) throw const SingBoxNotInitializedException();
  }

  /// Resets the singleton. Only for tests.
  @visibleForTesting
  Future<void> debugReset() async {
    await _stateSubscription?.cancel();
    await _notificationSubscription?.cancel();
    _stateSubscription = null;
    _notificationSubscription = null;
    _isInitialized = false;
    _initializing = null;
    _runtimeInfo = null;
    _state = SingBoxConnectionState.initial;
    _lastStats = null;
    _observer = const SingBoxNoOpObserver();
    configOptions = const SingBoxConfigOptions();
    reloadOnRulesChange = true;
    _mutation = Future<void>.value();
    _serviceQueue = Future<void>.value();
    _startWaiter?.cancel();
    _startWaiter = null;
  }

