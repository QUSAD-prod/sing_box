  /// Builds the final sing-box configuration for [input] without starting the
  /// tunnel. See the class documentation for the accepted input formats.
  ///
  /// [rules] defaults to the stored [getRoutingRules], [options] to
  /// [configOptions]. With `applyRules: false` a complete config is returned
  /// unchanged. [selectedTag] picks the initially selected outbound when
  /// several outbounds are wrapped into a selector.
  ///
  /// Throws a [SingBoxConfigException] when [input] cannot be understood.
  Future<String> buildConfig(
    String input, {
    SingBoxRoutingRules? rules,
    SingBoxConfigOptions? options,
    bool applyRules = true,
    String? selectedTag,
  }) async {
    final effectiveRules = rules ?? await getRoutingRules();
    return _build(
      input,
      rules: effectiveRules,
      options: options ?? configOptions,
      applyRules: applyRules,
      selectedTag: selectedTag,
    );
  }

  String _build(
    String input, {
    required SingBoxRoutingRules rules,
    required SingBoxConfigOptions options,
    required bool applyRules,
    String? selectedTag,
  }) {
    final trimmed = input.trim();
    if (trimmed.isEmpty) {
      throw const SingBoxConfigException('The configuration is empty.');
    }
    final builder = SingBoxConfigBuilder(options);
    try {
      if (trimmed.startsWith('{')) {
        final decoded = jsonDecode(trimmed);
        if (decoded is! Map) {
          throw const SingBoxConfigException('Expected a JSON object.');
        }
        final map = Map<String, dynamic>.from(decoded);
        final isFull =
            map.containsKey('outbounds') ||
            map.containsKey('inbounds') ||
            map.containsKey('route') ||
            map.containsKey('endpoints');
        if (isFull) {
          return jsonEncode(
            applyRules ? builder.apply(map, rules: rules) : map,
          );
        }
        return jsonEncode(
          builder.build([map], rules: rules, selectedTag: selectedTag),
        );
      }
      if (trimmed.startsWith('[')) {
        final decoded = jsonDecode(trimmed);
        if (decoded is! List) {
          throw const SingBoxConfigException('Expected a JSON array.');
        }
        final outbounds =
            decoded
                .whereType<Map<dynamic, dynamic>>()
                .map(Map<String, dynamic>.from)
                .toList();
        if (outbounds.isEmpty) {
          throw const SingBoxConfigException('The outbound list is empty.');
        }
        return jsonEncode(
          builder.build(outbounds, rules: rules, selectedTag: selectedTag),
        );
      }
      final outbounds = SingBoxShareLink.parseSubscription(trimmed);
      if (outbounds.isEmpty) {
        // Surface the parser's error for a single link.
        if (!trimmed.contains('\n')) SingBoxShareLink.parse(trimmed);
        throw const SingBoxConfigException(
          'No supported share links or JSON configuration found.',
        );
      }
      return jsonEncode(
        builder.build(
          outbounds.map((o) => o.json).toList(),
          rules: rules,
          selectedTag: selectedTag,
        ),
      );
    } on SingBoxException {
      rethrow;
    } on FormatException catch (e) {
      throw SingBoxConfigException(e.message);
    } on ArgumentError catch (e) {
      throw SingBoxConfigException('${e.message}');
    }
  }

