  /// Returns all stored server profiles.
  Future<List<SingBoxServerConfig>> getServerConfigs() async {
    final list = await _storage.readList(SingBoxStorage.keyServerConfigs);
    return (list ?? const [])
        .whereType<Map<dynamic, dynamic>>()
        .map(SingBoxServerConfig.fromMap)
        .toList();
  }

  Future<void> _writeServers(List<SingBoxServerConfig> servers) =>
      _storage.writeJson(
        SingBoxStorage.keyServerConfigs,
        servers.map((e) => e.toMap()).toList(),
      );

  /// Returns the profile with [configId], or `null`.
  Future<SingBoxServerConfig?> getServerConfig(String configId) async {
    for (final server in await getServerConfigs()) {
      if (server.id == configId) return server;
    }
    return null;
  }

  /// Stores a new profile. Returns `false` if a profile with the same id
  /// exists (use [updateServerConfig]).
  Future<bool> addServerConfig(SingBoxServerConfig config) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      if (servers.any((s) => s.id == config.id)) return false;
      await _writeServers([...servers, config]);
      _observer.onServerConfigAdded(config.id, config.name);
      return true;
    });
  }

  /// Replaces the stored profile with the same id. Returns `false` if it
  /// does not exist.
  Future<bool> updateServerConfig(SingBoxServerConfig config) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      final index = servers.indexWhere((s) => s.id == config.id);
      if (index < 0) return false;
      servers[index] = config;
      await _writeServers(servers);
      _observer.info('Server config updated', {'id': config.id});
      return true;
    });
  }

  /// Removes a profile. Clears the active server if it was the removed one.
  Future<bool> removeServerConfig(String configId) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      final remaining = servers.where((s) => s.id != configId).toList();
      if (remaining.length == servers.length) return false;
      await _writeServers(remaining);
      if (await _storage.readString(SingBoxStorage.keyActiveServerConfig) ==
          configId) {
        await _storage.writeString(SingBoxStorage.keyActiveServerConfig, null);
      }
      _observer.onServerConfigRemoved(configId);
      return true;
    });
  }

  /// Removes all profiles, or only those of [subscriptionId].
  Future<void> clearServerConfigs({String? subscriptionId}) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      await _writeServers(
        subscriptionId == null
            ? const []
            : servers.where((s) => s.subscriptionId != subscriptionId).toList(),
      );
    });
  }

  /// Imports share links or a subscription body (base64 or one link per
  /// line) as new profiles and returns them. Unsupported lines are skipped.
  Future<List<SingBoxServerConfig>> importServerConfigs(
    String content, {
    String? subscriptionId,
  }) {
    return _synchronized(() async {
      final outbounds = SingBoxShareLink.parseSubscription(content);
      final servers = await getServerConfigs();
      final ids = servers.map((s) => s.id).toSet();
      final imported = <SingBoxServerConfig>[];
      for (final outbound in outbounds) {
        var id = outbound.tag;
        var index = 2;
        while (ids.contains(id)) {
          id = '${outbound.tag}-${index++}';
        }
        ids.add(id);
        imported.add(
          SingBoxServerConfig.fromOutbound(
            outbound.json,
            id: id,
            name: outbound.name ?? outbound.tag,
            link: outbound.link,
            subscriptionId: subscriptionId,
          ),
        );
      }
      if (imported.isNotEmpty) {
        await _writeServers([...servers, ...imported]);
        for (final s in imported) {
          _observer.onServerConfigAdded(s.id, s.name);
        }
      }
      return imported;
    });
  }

  /// Marks the profile [configId] as active (`null` clears it). Returns
  /// `false` if no such profile exists.
  Future<bool> setActiveServerConfig(String? configId) async {
    if (configId != null && await getServerConfig(configId) == null) {
      return false;
    }
    await _setActiveId(configId);
    return true;
  }

  Future<void> _setActiveId(String? configId) async {
    await _storage.writeString(SingBoxStorage.keyActiveServerConfig, configId);
    _observer.onActiveServerConfigChanged(configId ?? '');
  }

  /// Returns the active profile, or `null`.
  Future<SingBoxServerConfig?> getActiveServerConfig() async {
    final id = await _storage.readString(SingBoxStorage.keyActiveServerConfig);
    return id == null ? null : getServerConfig(id);
  }

  /// Same as [getActiveServerConfig].
  @Deprecated('Use getActiveServerConfig() instead.')
  Future<SingBoxServerConfig?> getActiveSingBoxServerConfig() =>
      getActiveServerConfig();

  // ===========================================================================
  // Helpers
  // ===========================================================================

  Future<T> _synchronized<T>(Future<T> Function() action) {
    final result = _mutation.then((_) => action());
    _mutation = result.then<void>((_) {}, onError: (_) {});
    return result;
  }
}

/// Follows the tunnel state after one start request and completes
/// [outcome] when the tunnel connects, or fails it when the tunnel stops
/// first or the request is cancelled.
class _StartWaiter {
  _StartWaiter(Stream<SingBoxConnectionState> states, this._before) {
    _subscription = states.listen(_onState);
  }

  /// The state when the start was requested.
  final SingBoxConnectionState _before;
  late final StreamSubscription<SingBoxConnectionState> _subscription;
  final _completer = Completer<void>();
  bool _sawActive = false;
  bool _requested = false;
  String? _earlyError;

  Future<void> get outcome => _completer.future;

  void _onState(SingBoxConnectionState state) {
    if (_completer.isCompleted) return;
    switch (state.status) {
      case SingBoxConnectionStatus.connected:
        _completer.complete();
      case SingBoxConnectionStatus.connecting:
      case SingBoxConnectionStatus.disconnecting:
        _sawActive = true;
      case SingBoxConnectionStatus.disconnected:
        // Until the tunnel became active or the platform confirmed the
        // request, a plain "disconnected" belongs to the previous session.
        if (_sawActive || _requested) {
          _fail(state.error);
        } else if (state.error != null && state.error != _before.error) {
          _earlyError = state.error;
        }
    }
  }

  /// Called once the platform accepted the start request.
  void requested() {
    _requested = true;
    if (_earlyError != null) _fail(_earlyError);
  }

  void _fail(String? error) {
    if (_completer.isCompleted) return;
    _completer.completeError(
      SingBoxStartException(error ?? 'The tunnel stopped before it connected.'),
    );
  }

  void cancel() {
    if (_completer.isCompleted) return;
    _completer.completeError(
      const SingBoxCancelledException('The connection request was superseded.'),
    );
  }

  void dispose() {
    _subscription.cancel();
    // Nobody awaits a waiter that was cancelled before the platform call
    // returned; keep its error from becoming unhandled.
    _completer.future.ignore();
  }
}
