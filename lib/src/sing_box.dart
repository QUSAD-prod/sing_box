  /// Stores [rules]. When connected and [reloadOnRulesChange] is enabled the
  /// tunnel is reloaded so the rules take effect immediately.
  Future<void> saveRoutingRules(SingBoxRoutingRules rules) async {
    await _storage.writeJson(SingBoxStorage.keyRoutingRules, rules.toMap());
    _observer.info('Routing rules saved');
    if (reloadOnRulesChange && _isInitialized && _state.status.isActive) {
      try {
        await reapplyRules();
      } on SingBoxException catch (e, s) {
        _observer.error('Failed to re-apply routing rules', e, s);
      }
    }
