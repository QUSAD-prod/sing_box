  static bool _isValidDns(String address) {
    try {
      SingBoxDnsServer.parse(address, tag: 'validate');
      return true;
    } on FormatException {
      return false;
    }
  }

  /// Adds a remote DNS server: `1.1.1.1`, `tls://1.1.1.1`,
  /// `https://dns.google/dns-query`, `quic://dns.adguard.com`, … Returns
  /// whether the list changed (`false` for an invalid address).
  Future<bool> addDnsServer(String dnsServer) {
    final value = dnsServer.trim();
    return _addTo(
      (r) => r.dnsServers,
      (r, v) => r.copyWith(dnsServers: v),
      _isValidDns(value) ? value : null,
    );
  }

  /// Removes a DNS server.
  Future<bool> removeDnsServer(String dnsServer) => _removeFrom(
    (r) => r.dnsServers,
    (r, v) => r.copyWith(dnsServers: v),
    dnsServer.trim(),
  );

  /// Custom DNS servers (empty = the defaults of [SingBoxDnsOptions]).
  Future<List<String>> getDnsServers() async =>
      (await getRoutingRules()).dnsServers;

  /// Replaces the custom DNS servers. Returns `false` (and changes nothing)
  /// if any address is invalid.
  Future<bool> setDnsServers(List<String> dnsServers) async {
    final values = dnsServers.map((e) => e.trim()).where((e) => e.isNotEmpty);
    if (!values.every(_isValidDns)) return false;
    await updateRoutingRules(
      (r) => r.copyWith(dnsServers: values.toSet().toList()),
    );
    return true;
  }

