  /// Replaces the stored profile with the same id. Returns `false` if it
  /// does not exist.
  Future<bool> updateServerConfig(SingBoxServerConfig config) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      final index = servers.indexWhere((s) => s.id == config.id);
      if (index < 0) return false;
      servers[index] = config;
      await _writeServers(servers);
      _observer.info('Server config updated', {'id': config.id});
      return true;
    });
  }

  /// Removes a profile. Clears the active server if it was the removed one.
  Future<bool> removeServerConfig(String configId) {
    return _synchronized(() async {
      final servers = await getServerConfigs();
      final remaining = servers.where((s) => s.id != configId).toList();
      if (remaining.length == servers.length) return false;
      await _writeServers(remaining);
      if (await _storage.readString(SingBoxStorage.keyActiveServerConfig) ==
          configId) {
        await _storage.writeString(SingBoxStorage.keyActiveServerConfig, null);
      }
      _observer.onServerConfigRemoved(configId);
      return true;
    });
  }

