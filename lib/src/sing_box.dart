    SingBoxRoutingRules Function(SingBoxRoutingRules rules) update,
  ) {
    return _synchronized(() async {
      final current = await getRoutingRules();
      final updated = update(current);
      if (updated == current) return false;
      await saveRoutingRules(updated);
      return true;
    });
  }

  Future<bool> _addTo(
    List<String> Function(SingBoxRoutingRules r) get,
    SingBoxRoutingRules Function(SingBoxRoutingRules r, List<String> v) set,
    String? value,
  ) {
    if (value == null) return Future<bool>.value(false);
    return updateRoutingRules((r) {
      final list = get(r);
      if (list.contains(value)) return r;
      return set(r, [...list, value]);
    });
  }

  Future<bool> _removeFrom(
    List<String> Function(SingBoxRoutingRules r) get,
    SingBoxRoutingRules Function(SingBoxRoutingRules r, List<String> v) set,
    String value,
  ) {
    return updateRoutingRules((r) {
      final list = get(r);
      if (!list.contains(value)) return r;
      return set(r, list.where((e) => e != value).toList());
    });
  }

