  /// Measures the latency of the outbound [tag] through the running tunnel
  /// (HTTP request through the proxy, see [SingBoxConfigOptions.urlTestUrl]).
  Future<SingBoxPingResult> pingOutbound(
    String tag, {
    Duration timeout = const Duration(seconds: 15),
  }) async {
    _ensureInitialized();
    if (!isConnected) {
      return SingBoxPingResult.failure('Not connected to VPN', tag: tag);
    }
    final address = await _serverAddressOf(tag);
    final startedAt = DateTime.now().subtract(const Duration(seconds: 1));
    try {
      final resultFuture = watchOutbounds()
          .expand((items) => items)
          .firstWhere(
            (item) =>
                item.tag == tag &&
                item.urlTestTime != null &&
                !item.urlTestTime!.isBefore(startedAt),
          )
          .timeout(timeout);
      await urlTest(tag);
      final item = await resultFuture;
      return item.urlTestDelay == null
          ? SingBoxPingResult.failure('URL test failed', tag: tag, address: address)
          : SingBoxPingResult(
              ping: item.urlTestDelay!,
              success: true,
              tag: tag,
              address: address,
            );
    } on TimeoutException {
      return SingBoxPingResult.failure(
        'URL test timed out',
        tag: tag,
        address: address,
      );
    } on SingBoxException catch (e) {
      return SingBoxPingResult.failure(e.message, tag: tag, address: address);
    }
  }

  /// Measures the latency of the server currently used by the main selector.
  Future<SingBoxPingResult> pingCurrentServer({
    Duration timeout = const Duration(seconds: 15),
  }) async {
    _ensureInitialized();
    if (!isConnected) {
      return const SingBoxPingResult.failure('Not connected to VPN');
    }
    final tag = await currentOutboundTag();
    if (tag == null) {
      return const SingBoxPingResult.failure('No proxy outbound found');
    }
    return pingOutbound(tag, timeout: timeout);
  }

  /// Runs a URL test of all members of [groupTag] and returns the group once
  /// every member has a fresh result (or after [timeout]).
  Future<SingBoxOutboundGroup?> testGroup(
    String groupTag, {
    Duration timeout = const Duration(seconds: 20),
  }) async {
    _ensureInitialized();
    if (!isConnected) return null;
    final startedAt = DateTime.now().subtract(const Duration(seconds: 1));
    SingBoxOutboundGroup? latest;
    bool fresh(SingBoxOutboundItem i) =>
        i.urlTestTime != null && !i.urlTestTime!.isBefore(startedAt);
    final done = watchGroups()
        .map((groups) {
          for (final g in groups) {
            if (g.tag == groupTag) return latest = g;
          }
          return null;
        })
        .firstWhere(
          (g) =>
              g != null &&
              g.items
                  .where((i) => !_builtinTypes.contains(i.type))
                  .every(fresh),
        )
        .timeout(timeout);
    await urlTest(groupTag);
    try {
      return await done;
    } on TimeoutException {
      return latest;
    }
  }

  static const _builtinTypes = {'direct', 'block', 'dns', 'selector', 'urltest'};

  /// Resolves the outbound currently selected by the main group (following
  /// nested groups such as `proxy` → `auto` → server), or `null`.
  Future<String?> currentOutboundTag({
    Duration timeout = const Duration(seconds: 5),
  }) async {
    _ensureInitialized();
    List<SingBoxOutboundGroup> groups;
    try {
      groups = await watchGroups().first.timeout(timeout);
    } on Object {
      groups = const [];
    }
    if (groups.isNotEmpty) {
      final byTag = {for (final g in groups) g.tag: g};
      var group =
          byTag[SingBoxConfigBuilder.proxyTag] ??
          groups.firstWhere((g) => g.selectable, orElse: () => groups.first);
      final visited = <String>{};
      while (visited.add(group.tag)) {
        final next = byTag[group.selected];
        if (next == null) {
          return group.selected.isEmpty ? null : group.selected;
        }
        group = next;
      }
    }
    final outbound = await _firstProxyOutbound();
    return outbound?['tag'] as String?;
  }

  Future<Map<String, dynamic>?> _firstProxyOutbound([String? tag]) async {
    final config = await _platform.getLastConfig();
    if (config == null) return null;
    try {
      final decoded = jsonDecode(config);
      final outbounds = decoded is Map ? decoded['outbounds'] : null;
      if (outbounds is! List) return null;
      for (final o in outbounds.whereType<Map<dynamic, dynamic>>()) {
        if (tag != null ? o['tag'] == tag : !_builtinTypes.contains(o['type'])) {
          return Map<String, dynamic>.from(o);
        }
      }
    } on FormatException {
      return null;
    }
    return null;
  }

  Future<String?> _serverAddressOf(String tag) async {
    final outbound = await _firstProxyOutbound(tag);
    return outbound?['server'] as String?;
  }

