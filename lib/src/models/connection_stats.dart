/// Real-time traffic and runtime statistics of the running sing-box core.
///
/// Emitted about once per second by `SingBox.watchConnectionStats()` while
/// the tunnel is connected.
class SingBoxConnectionStats {
  /// Creates a statistics snapshot.
  const SingBoxConnectionStats({
    this.uploadSpeed = 0,
    this.downloadSpeed = 0,
    this.uploadTotal = 0,
    this.downloadTotal = 0,
    this.connectionsIn = 0,
    this.connectionsOut = 0,
    this.memory = 0,
    this.goroutines = 0,
    this.trafficAvailable = false,
    this.duration = Duration.zero,
  });

  /// Statistics with every counter at zero.
  static const empty = SingBoxConnectionStats();

  /// Parses an event of the `sing_box/stats` channel.
  factory SingBoxConnectionStats.fromMap(
    Map<dynamic, dynamic> map, {
    Duration duration = Duration.zero,
  }) {
    int read(String key, [String? legacyKey]) {
      final value = map[key] ?? (legacyKey == null ? null : map[legacyKey]);
      return value is num ? value.toInt() : 0;
    }

    return SingBoxConnectionStats(
      uploadSpeed: read('uplink', 'uploadSpeed'),
      downloadSpeed: read('downlink', 'downloadSpeed'),
      uploadTotal: read('uplinkTotal', 'bytesSent'),
      downloadTotal: read('downlinkTotal', 'bytesReceived'),
      connectionsIn: read('connectionsIn'),
      connectionsOut: read('connectionsOut'),
      memory: read('memory'),
      goroutines: read('goroutines'),
      trafficAvailable: map['trafficAvailable'] as bool? ?? false,
      duration: duration,
    );
  }

  /// Current upload speed in bytes per second.
  final int uploadSpeed;

  /// Current download speed in bytes per second.
  final int downloadSpeed;

  /// Bytes uploaded since the tunnel started.
  final int uploadTotal;

  /// Bytes downloaded since the tunnel started.
  final int downloadTotal;

  /// Number of inbound connections currently tracked by sing-box.
  final int connectionsIn;

  /// Number of outbound connections currently tracked by sing-box.
  final int connectionsOut;

  /// Memory used by the sing-box core, in bytes.
  final int memory;

  /// Number of goroutines of the sing-box core (a debugging aid).
  final int goroutines;

  /// Whether traffic statistics are available. They require the clash API or
  /// the V2Ray API to be enabled in the configuration; configs generated by
  /// `SingBoxConfigBuilder` always enable them.
  final bool trafficAvailable;

  /// How long the tunnel has been connected.
  final Duration duration;

  /// Total bytes sent. Same as [uploadTotal].
  @Deprecated('Use uploadTotal instead.')
  int get bytesSent => uploadTotal;

  /// Total bytes received. Same as [downloadTotal].
  @Deprecated('Use downloadTotal instead.')
  int get bytesReceived => downloadTotal;

  /// Connection duration in milliseconds. Same as [duration].
  @Deprecated('Use duration instead.')
  int get connectionDuration => duration.inMilliseconds;

  /// Returns a copy with the given fields replaced.
  SingBoxConnectionStats copyWith({
    int? uploadSpeed,
    int? downloadSpeed,
    int? uploadTotal,
    int? downloadTotal,
    int? connectionsIn,
    int? connectionsOut,
    int? memory,
    int? goroutines,
    bool? trafficAvailable,
    Duration? duration,
  }) {
    return SingBoxConnectionStats(
      uploadSpeed: uploadSpeed ?? this.uploadSpeed,
      downloadSpeed: downloadSpeed ?? this.downloadSpeed,
      uploadTotal: uploadTotal ?? this.uploadTotal,
      downloadTotal: downloadTotal ?? this.downloadTotal,
      connectionsIn: connectionsIn ?? this.connectionsIn,
      connectionsOut: connectionsOut ?? this.connectionsOut,
      memory: memory ?? this.memory,
      goroutines: goroutines ?? this.goroutines,
      trafficAvailable: trafficAvailable ?? this.trafficAvailable,
      duration: duration ?? this.duration,
    );
  }

  /// Serializes the statistics using the wire format.
  Map<String, dynamic> toMap() => {
    'uplink': uploadSpeed,
    'downlink': downloadSpeed,
    'uplinkTotal': uploadTotal,
    'downlinkTotal': downloadTotal,
    'connectionsIn': connectionsIn,
    'connectionsOut': connectionsOut,
    'memory': memory,
    'goroutines': goroutines,
    'trafficAvailable': trafficAvailable,
    'durationMs': duration.inMilliseconds,
  };

  @override
  bool operator ==(Object other) =>
      other is SingBoxConnectionStats &&
      other.uploadSpeed == uploadSpeed &&
      other.downloadSpeed == downloadSpeed &&
      other.uploadTotal == uploadTotal &&
      other.downloadTotal == downloadTotal &&
      other.connectionsIn == connectionsIn &&
      other.connectionsOut == connectionsOut &&
      other.memory == memory &&
      other.goroutines == goroutines &&
      other.trafficAvailable == trafficAvailable &&
      other.duration == duration;

  @override
  int get hashCode => Object.hash(
    uploadSpeed,
    downloadSpeed,
    uploadTotal,
    downloadTotal,
    connectionsIn,
    connectionsOut,
    memory,
    goroutines,
    trafficAvailable,
    duration,
  );

  @override
  String toString() =>
      'SingBoxConnectionStats(up: $uploadSpeed B/s, down: $downloadSpeed B/s, '
      'upTotal: $uploadTotal, downTotal: $downloadTotal, '
      'connections: $connectionsIn/$connectionsOut, memory: $memory, '
      'duration: $duration)';
}
