// `dart run sing_box:setup_ios`: adds the Packet Tunnel extension target to
// a Flutter iOS project without Ruby gems. Internal; see bin/setup_ios.dart.

import 'dart:io';

import 'pbxproj.dart';

/// Options of [setupIos].
class SetupIosOptions {
  /// Creates options; `null` values use the defaults of the Runner target.
  const SetupIosOptions({
    required this.project,
    this.target = 'PacketTunnel',
    this.bundleId,
    this.appGroup,
    this.team,
  });

  /// Path of `Runner.xcodeproj`.
  final String project;

  /// Name of the extension target.
  final String target;

  /// Extension bundle id (default `<app bundle id>.<target>`).
  final String? bundleId;

  /// App Group (default `group.<app bundle id>`).
  final String? appGroup;

  /// `DEVELOPMENT_TEAM` (default: the Runner's team).
  final String? team;
}

/// How [setupIos] linked the `SingBoxTunnel` library to the extension.
enum TunnelLinking {
  /// Through Flutter's Swift package (`FlutterGeneratedPluginSwiftPackage`).
  swiftPackageManager,

  /// Through `pod 'SingBoxTunnel'` in the Podfile.
  cocoaPods,

  /// Not linked: neither Flutter's Swift package nor a Podfile was found.
  none,
}

/// Adds or updates the Packet Tunnel extension (idempotent) and returns how
/// the tunnel library is linked. [log] receives progress lines.
TunnelLinking setupIos(SetupIosOptions options, void Function(String) log) {
  final projectDir = Directory(options.project);
  final pbxFile = File('${projectDir.path}/project.pbxproj');
  if (!pbxFile.existsSync()) {
    throw StateError('${pbxFile.path} not found');
  }
  final iosDir = projectDir.parent.path;
  final name = options.target;
  final pbx = PbxProject(pbxFile.readAsStringSync());

  final runnerId = pbx.targetId('Runner');
  if (runnerId == null) throw StateError('No Runner target');
  final runner = pbx.objects[runnerId]!;
  final runnerConfigListId = runner['buildConfigurationList']! as String;
  final runnerConfigs = pbx.configurations(runnerConfigListId);
  final runnerSettings = runnerConfigs.values.first;
  final appBundleId = runnerSettings['PRODUCT_BUNDLE_IDENTIFIER'] as String?;
  if (appBundleId == null) {
    throw StateError('Runner has no PRODUCT_BUNDLE_IDENTIFIER');
  }
  final bundleId = options.bundleId ?? '$appBundleId.$name';
  final appGroup = options.appGroup ?? 'group.$appBundleId';
  final team = options.team ?? runnerSettings['DEVELOPMENT_TEAM'] as String?;
  final configNames =
      pbx
          .configurations(pbx.project['buildConfigurationList']! as String)
          .keys
          .toList();

  // --- Files
  final extDir = Directory('$iosDir/$name')..createSync(recursive: true);
  void writeUnlessExists(String path, String content) {
    final file = File(path);
    if (file.existsSync()) return;
    file.writeAsStringSync(content);
    log('created $path');
  }

  writeUnlessExists('${extDir.path}/PacketTunnelProvider.swift', '''
import SingBoxTunnel

/// The sing-box Packet Tunnel provider. All logic lives in the plugin's
/// `SingBoxTunnel` library; override its methods only if you need to.
class PacketTunnelProvider: SingBoxPacketTunnelProvider {}
''');
  writeUnlessExists('${extDir.path}/Info.plist', _infoPlist(name));
  mergeEntitlements(File('${extDir.path}/$name.entitlements'), appGroup);
  for (final config in configNames) {
    File('${extDir.path}/$config.xcconfig').writeAsStringSync('''
// Generated by `dart run sing_box:setup_ios`.
#include? "../Pods/Target Support Files/Pods-$name/Pods-$name.${config.toLowerCase()}.xcconfig"
// FLUTTER_BUILD_NAME / FLUTTER_BUILD_NUMBER keep the extension version in sync with the app.
#include "../Flutter/Generated.xcconfig"
SING_BOX_APP_GROUP = $appGroup
''');
  }

  // --- Runner entitlements
  final runnerConfigIds = pbx.configurationIds(runnerConfigListId);
  for (final MapEntry(key: config, value: settings) in runnerConfigs.entries) {
    var path = settings['CODE_SIGN_ENTITLEMENTS'] as String?;
    if (path == null) {
      path = 'Runner/Runner.entitlements';
      pbx.setBuildSetting(
        runnerConfigIds[config]!,
        'CODE_SIGN_ENTITLEMENTS',
        path,
      );
    }
    mergeEntitlements(File('$iosDir/$path'), appGroup);
  }
  _addRunnerEntitlementsReference(pbx);

  // --- Extension target
  var targetId = pbx.targetId(name);
  if (targetId == null) {
    targetId = _addTarget(
      pbx,
      name: name,
      runnerId: runnerId,
      configNames: configNames,
      settings:
          (config) => {
            'APPLICATION_EXTENSION_API_ONLY': 'YES',
            'CODE_SIGN_ENTITLEMENTS': '$name/$name.entitlements',
            'CODE_SIGN_STYLE': 'Automatic',
            if (team != null) 'DEVELOPMENT_TEAM': team,
            'ENABLE_BITCODE': 'NO',
            'GENERATE_INFOPLIST_FILE': 'NO',
            'INFOPLIST_FILE': '$name/Info.plist',
            'IPHONEOS_DEPLOYMENT_TARGET': '15.0',
            'PRODUCT_BUNDLE_IDENTIFIER': bundleId,
            'PRODUCT_NAME': r'$(TARGET_NAME)',
            'SDKROOT': 'iphoneos',
            'SKIP_INSTALL': 'YES',
            'SWIFT_VERSION': '5.0',
            'TARGETED_DEVICE_FAMILY': '1,2',
            if (config != 'Debug') 'VALIDATE_PRODUCT': 'YES',
          },
    );
    log('added target $name');
  }

  // --- Linking
  final podfile = File('$iosDir/Podfile');
  final podfileText = podfile.existsSync() ? podfile.readAsStringSync() : null;
  // With Swift Package Manager disabled Flutter still generates its package,
  // but without plugin dependencies.
  final generated = File(
    '$iosDir/Flutter/ephemeral/Packages/FlutterGeneratedPluginSwiftPackage/Package.swift',
  );
  final flutterPackage =
      generated.existsSync() &&
              generated.readAsStringSync().contains('package: "sing_box"')
          ? pbx.localPackageId('FlutterGeneratedPluginSwiftPackage')
          : null;
  final TunnelLinking linking;
  if (podfileText != null && podfileText.contains("pod 'SingBoxTunnel'")) {
    // Linked by CocoaPods already; linking it twice duplicates symbols.
    linking = TunnelLinking.cocoaPods;
  } else if (flutterPackage != null) {
    _linkSwiftPackageProduct(pbx, targetId, flutterPackage, 'SingBoxTunnel');
    linking = TunnelLinking.swiftPackageManager;
  } else if (podfileText != null) {
    podfile.writeAsStringSync(_withPod(podfileText, name));
    log('added the $name target to ${podfile.path}');
    linking = TunnelLinking.cocoaPods;
  } else {
    linking = TunnelLinking.none;
  }

  pbxFile.writeAsStringSync(pbx.text);
  log('updated ${pbxFile.path} ($name: $bundleId, App Group $appGroup)');
  return linking;
}

String _comment(String id, Map<String, Map<String, Object?>> all) =>
    all[id]?['name'] as String? ?? all[id]?['path'] as String? ?? '';

String _addTarget(
  PbxProject pbx, {
  required String name,
  required String runnerId,
  required List<String> configNames,
  required Map<String, String> Function(String config) settings,
}) {
  final ids = {
    for (final key in [
      'target',
      'product',
      'group',
      'source',
      'sourceBuild',
      'info',
      'entitlements',
      'sources',
      'frameworks',
      'resources',
      'configList',
      'proxy',
      'dependency',
      'embed',
      'embedBuild',
    ])
      key: pbx.newId(),
  };
  final xcconfigIds = {for (final c in configNames) c: pbx.newId()};
  final configIds = {for (final c in configNames) c: pbx.newId()};
  final q = PbxProject.quote;

  pbx.addObjects(
    'PBXFileReference',
    [
      '\t\t${ids['product']} /* $name.appex */ = {isa = PBXFileReference; explicitFileType = "wrapper.app-extension"; includeInIndex = 0; path = $name.appex; sourceTree = BUILT_PRODUCTS_DIR; };\n',
      '\t\t${ids['source']} /* PacketTunnelProvider.swift */ = {isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = PacketTunnelProvider.swift; sourceTree = "<group>"; };\n',
      '\t\t${ids['info']} /* Info.plist */ = {isa = PBXFileReference; lastKnownFileType = text.plist.xml; path = Info.plist; sourceTree = "<group>"; };\n',
      '\t\t${ids['entitlements']} /* $name.entitlements */ = {isa = PBXFileReference; lastKnownFileType = text.plist.entitlements; path = $name.entitlements; sourceTree = "<group>"; };\n',
      for (final c in configNames)
        '\t\t${xcconfigIds[c]} /* $c.xcconfig */ = {isa = PBXFileReference; lastKnownFileType = text.xcconfig; path = $c.xcconfig; sourceTree = "<group>"; };\n',
    ].join(),
  );
  pbx.addObjects(
    'PBXBuildFile',
    [
      '\t\t${ids['sourceBuild']} /* PacketTunnelProvider.swift in Sources */ = {isa = PBXBuildFile; fileRef = ${ids['source']} /* PacketTunnelProvider.swift */; };\n',
      '\t\t${ids['embedBuild']} /* $name.appex in Embed Foundation Extensions */ = {isa = PBXBuildFile; fileRef = ${ids['product']} /* $name.appex */; settings = {ATTRIBUTES = (RemoveHeadersOnCopy, ); }; };\n',
    ].join(),
  );
  pbx.addObjects('PBXGroup', '''
\t\t${ids['group']} /* $name */ = {
\t\t\tisa = PBXGroup;
\t\t\tchildren = (
\t\t\t\t${ids['source']} /* PacketTunnelProvider.swift */,
\t\t\t\t${ids['info']} /* Info.plist */,
\t\t\t\t${ids['entitlements']} /* $name.entitlements */,
${[for (final c in configNames) '\t\t\t\t${xcconfigIds[c]} /* $c.xcconfig */,\n'].join()}\t\t\t);
\t\t\tpath = $name;
\t\t\tsourceTree = "<group>";
\t\t};
''');
  String phase(String isa, String id, String title, List<String> files) => '''
\t\t$id /* $title */ = {
\t\t\tisa = $isa;
\t\t\tbuildActionMask = 2147483647;
\t\t\tfiles = (
${[for (final f in files) '\t\t\t\t$f,\n'].join()}\t\t\t);
\t\t\trunOnlyForDeploymentPostprocessing = 0;
\t\t};
''';
  pbx.addObjects(
    'PBXSourcesBuildPhase',
    phase('PBXSourcesBuildPhase', ids['sources']!, 'Sources', [
      '${ids['sourceBuild']} /* PacketTunnelProvider.swift in Sources */',
    ]),
  );
  pbx.addObjects(
    'PBXFrameworksBuildPhase',
    phase('PBXFrameworksBuildPhase', ids['frameworks']!, 'Frameworks', []),
  );
  pbx.addObjects(
    'PBXResourcesBuildPhase',
    phase('PBXResourcesBuildPhase', ids['resources']!, 'Resources', []),
  );
  pbx.addObjects(
    'XCBuildConfiguration',
    [
      for (final c in configNames)
        '''
\t\t${configIds[c]} /* $c */ = {
\t\t\tisa = XCBuildConfiguration;
\t\t\tbaseConfigurationReference = ${xcconfigIds[c]} /* $c.xcconfig */;
\t\t\tbuildSettings = {
${[for (final MapEntry(:key, :value) in settings(c).entries) '\t\t\t\t$key = ${q(value)};\n'].join()}\t\t\t\tLD_RUNPATH_SEARCH_PATHS = (
\t\t\t\t\t"\$(inherited)",
\t\t\t\t\t"@executable_path/Frameworks",
\t\t\t\t\t"@executable_path/../../Frameworks",
\t\t\t\t);
\t\t\t};
\t\t\tname = $c;
\t\t};
''',
    ].join(),
  );
  pbx.addObjects('XCConfigurationList', '''
\t\t${ids['configList']} /* Build configuration list for PBXNativeTarget "$name" */ = {
\t\t\tisa = XCConfigurationList;
\t\t\tbuildConfigurations = (
${[for (final c in configNames) '\t\t\t\t${configIds[c]} /* $c */,\n'].join()}\t\t\t);
\t\t\tdefaultConfigurationIsVisible = 0;
\t\t\tdefaultConfigurationName = Release;
\t\t};
''');
  pbx.addObjects('PBXNativeTarget', '''
\t\t${ids['target']} /* $name */ = {
\t\t\tisa = PBXNativeTarget;
\t\t\tbuildConfigurationList = ${ids['configList']} /* Build configuration list for PBXNativeTarget "$name" */;
\t\t\tbuildPhases = (
\t\t\t\t${ids['sources']} /* Sources */,
\t\t\t\t${ids['frameworks']} /* Frameworks */,
\t\t\t\t${ids['resources']} /* Resources */,
\t\t\t);
\t\t\tbuildRules = (
\t\t\t);
\t\t\tdependencies = (
\t\t\t);
\t\t\tname = $name;
\t\t\tproductName = $name;
\t\t\tproductReference = ${ids['product']} /* $name.appex */;
\t\t\tproductType = "com.apple.product-type.app-extension";
\t\t};
''');
  pbx.addObjects('PBXContainerItemProxy', '''
\t\t${ids['proxy']} /* PBXContainerItemProxy */ = {
\t\t\tisa = PBXContainerItemProxy;
\t\t\tcontainerPortal = ${pbx.rootId} /* Project object */;
\t\t\tproxyType = 1;
\t\t\tremoteGlobalIDString = ${ids['target']};
\t\t\tremoteInfo = $name;
\t\t};
''');
  pbx.addObjects('PBXTargetDependency', '''
\t\t${ids['dependency']} /* PBXTargetDependency */ = {
\t\t\tisa = PBXTargetDependency;
\t\t\ttarget = ${ids['target']} /* $name */;
\t\t\ttargetProxy = ${ids['proxy']} /* PBXContainerItemProxy */;
\t\t};
''');
  pbx.addObjects('PBXCopyFilesBuildPhase', '''
\t\t${ids['embed']} /* Embed Foundation Extensions */ = {
\t\t\tisa = PBXCopyFilesBuildPhase;
\t\t\tbuildActionMask = 2147483647;
\t\t\tdstPath = "";
\t\t\tdstSubfolderSpec = 13;
\t\t\tfiles = (
\t\t\t\t${ids['embedBuild']} /* $name.appex in Embed Foundation Extensions */,
\t\t\t);
\t\t\tname = "Embed Foundation Extensions";
\t\t\trunOnlyForDeploymentPostprocessing = 0;
\t\t};
''');

  final all = pbx.objects;
  final project = pbx.project;
  pbx.addToList(pbx.rootId, 'targets', '${ids['target']} /* $name */,');
  pbx.addToList(
    project['mainGroup']! as String,
    'children',
    '${ids['group']} /* $name */,',
  );
  final products = project['productRefGroup'] as String?;
  if (products != null) {
    pbx.addToList(products, 'children', '${ids['product']} /* $name.appex */,');
  }
  pbx.addToList(
    runnerId,
    'dependencies',
    '${ids['dependency']} /* PBXTargetDependency */,',
  );
  // The embed phase must run before Flutter's "Thin Binary" script,
  // otherwise Xcode reports a dependency cycle inside Runner.
  final phases = (all[runnerId]!['buildPhases']! as List).cast<String>();
  final thin = phases.indexWhere((id) => all[id]?['name'] == 'Thin Binary');
  pbx.addToList(
    runnerId,
    'buildPhases',
    '${ids['embed']} /* Embed Foundation Extensions */,',
    after:
        thin > 0
            ? '${phases[thin - 1]} /* ${_comment(phases[thin - 1], all)}'
            : null,
  );
  return ids['target']!;
}

void _addRunnerEntitlementsReference(PbxProject pbx) {
  final all = pbx.objects;
  final mainChildren =
      (all[pbx.project['mainGroup']]!['children']! as List).cast<String>();
  final runnerGroup = mainChildren.firstWhere(
    (id) => all[id]?['path'] == 'Runner' || all[id]?['name'] == 'Runner',
    orElse: () => '',
  );
  if (runnerGroup.isEmpty) return;
  final children = (all[runnerGroup]!['children']! as List).cast<String>();
  if (children.any((id) => all[id]?['path'] == 'Runner.entitlements')) return;
  final id = pbx.newId();
  pbx.addObjects(
    'PBXFileReference',
    '\t\t$id /* Runner.entitlements */ = {isa = PBXFileReference; lastKnownFileType = text.plist.entitlements; path = Runner.entitlements; sourceTree = "<group>"; };\n',
  );
  pbx.addToList(runnerGroup, 'children', '$id /* Runner.entitlements */,');
}

/// Links [product] of the local package [packageId] to [targetId] (a product
/// of a dependency of that package works too: Xcode resolves the graph).
void _linkSwiftPackageProduct(
  PbxProject pbx,
  String targetId,
  String packageId,
  String product,
) {
  final all = pbx.objects;
  final existing =
      (all[targetId]!['packageProductDependencies'] as List? ?? const [])
          .cast<String>();
  if (existing.any((id) => all[id]?['productName'] == product)) return;
  final dependency = pbx.newId();
  final buildFile = pbx.newId();
  pbx.addObjects('XCSwiftPackageProductDependency', '''
\t\t$dependency /* $product */ = {
\t\t\tisa = XCSwiftPackageProductDependency;
\t\t\tpackage = $packageId;
\t\t\tproductName = $product;
\t\t};
''');
  pbx.addObjects(
    'PBXBuildFile',
    '\t\t$buildFile /* $product in Frameworks */ = {isa = PBXBuildFile; productRef = $dependency /* $product */; };\n',
  );
  pbx.addToList(
    targetId,
    'packageProductDependencies',
    '$dependency /* $product */,',
  );
  final frameworks = (all[targetId]!['buildPhases']! as List)
      .cast<String>()
      .firstWhere((id) => all[id]?['isa'] == 'PBXFrameworksBuildPhase');
  pbx.addToList(
    frameworks,
    'files',
    '$buildFile /* $product in Frameworks */,',
  );
}

String _withPod(String podfile, String name) {
  if (podfile.contains("target '$name'")) return podfile;
  final block = '''

# sing_box Packet Tunnel extension. Static linkage: works whether the app
# links the plugin through Swift Package Manager or CocoaPods.
target '$name' do
  use_frameworks! :linkage => :static
  pod 'SingBoxTunnel', :path => '.symlinks/plugins/sing_box/ios'
end
''';
  final index = podfile.indexOf('\npost_install do');
  return index >= 0
      ? podfile.replaceRange(index, index, block)
      : podfile + block;
}

/// Adds the Network Extension (packet tunnel) and App Group entitlements to
/// the plist [file], creating it when needed.
void mergeEntitlements(File file, String appGroup) {
  const networkExtension = 'com.apple.developer.networking.networkextension';
  const appGroups = 'com.apple.security.application-groups';
  var text =
      file.existsSync()
          ? file.readAsStringSync()
          : '''
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
</dict>
</plist>
''';
  final original = text;
  for (final (key, value) in [
    (networkExtension, 'packet-tunnel-provider'),
    (appGroups, appGroup),
  ]) {
    final keyMatch = RegExp(
      '<key>${RegExp.escape(key)}</key>\\s*<array>([\\s\\S]*?)</array>',
    ).firstMatch(text);
    if (keyMatch == null) {
      final close = text.lastIndexOf('</dict>');
      text = text.replaceRange(
        close,
        close,
        '\t<key>$key</key>\n\t<array>\n\t\t<string>$value</string>\n\t</array>\n',
      );
    } else if (!keyMatch.group(1)!.contains('<string>$value</string>')) {
      final at = keyMatch.end - '</array>'.length;
      text = text.replaceRange(at, at, '\t<string>$value</string>\n\t');
    }
  }
  if (text != original) {
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(text);
  }
}

String _infoPlist(String name) => '''
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>\$(DEVELOPMENT_LANGUAGE)</string>
	<key>CFBundleDisplayName</key>
	<string>$name</string>
	<key>CFBundleExecutable</key>
	<string>\$(EXECUTABLE_NAME)</string>
	<key>CFBundleIdentifier</key>
	<string>\$(PRODUCT_BUNDLE_IDENTIFIER)</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>\$(PRODUCT_NAME)</string>
	<key>CFBundlePackageType</key>
	<string>\$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
	<key>CFBundleShortVersionString</key>
	<string>\$(FLUTTER_BUILD_NAME)</string>
	<key>CFBundleVersion</key>
	<string>\$(FLUTTER_BUILD_NUMBER)</string>
	<key>NSExtension</key>
	<dict>
		<key>NSExtensionPointIdentifier</key>
		<string>com.apple.networkextension.packet-tunnel</string>
		<key>NSExtensionPrincipalClass</key>
		<string>\$(PRODUCT_MODULE_NAME).PacketTunnelProvider</string>
	</dict>
	<key>SingBoxAppGroup</key>
	<string>\$(SING_BOX_APP_GROUP)</string>
</dict>
</plist>
''';
